DO $$
DECLARE table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'omnia_statuses', 'omnia_ticket_statuses', 'omnia_admissao_statuses',
    'omnia_rescisao_statuses', 'omnia_atas', 'omnia_comments', 'omnia_attachments',
    'omnia_ticket_recurrences', 'omnia_tickets', 'omnia_ticket_comments',
    'omnia_ticket_attachments', 'omnia_admissoes', 'omnia_rescisoes',
    'omnia_balancete_csv_import_batches', 'omnia_protocolos', 'omnia_balancetes',
    'omnia_balancete_attachments'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', 'Authenticated users can read local data', table_name);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (true) WITH CHECK (true)', 'Authenticated users can read local data', table_name);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated', table_name);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO service_role', table_name);
  END LOOP;
END $$;
