CREATE TABLE IF NOT EXISTS public.omnia_rescisoes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  title TEXT NOT NULL,
  description TEXT,
  status_id UUID NOT NULL CONSTRAINT omnia_demissoes_status_id_fkey REFERENCES public.omnia_rescisao_statuses(id),
  priority TEXT NOT NULL DEFAULT 'MEDIA',
  due_date DATE,
  assigned_to UUID CONSTRAINT omnia_demissoes_assigned_to_fkey REFERENCES public.omnia_users(id),
  created_by UUID CONSTRAINT omnia_demissoes_created_by_fkey REFERENCES public.omnia_users(id),
  is_private BOOLEAN NOT NULL DEFAULT false,
  tags TEXT[] DEFAULT ARRAY[]::TEXT[],
  comment_count INTEGER NOT NULL DEFAULT 0,
  attachment_count INTEGER NOT NULL DEFAULT 0,
  ticket_octa TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'omnia_rescisoes_assigned_to_fkey' AND conrelid = 'public.omnia_rescisoes'::regclass)
     AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'omnia_demissoes_assigned_to_fkey' AND conrelid = 'public.omnia_rescisoes'::regclass) THEN
    ALTER TABLE public.omnia_rescisoes RENAME CONSTRAINT omnia_rescisoes_assigned_to_fkey TO omnia_demissoes_assigned_to_fkey;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'omnia_rescisoes_created_by_fkey' AND conrelid = 'public.omnia_rescisoes'::regclass)
     AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'omnia_demissoes_created_by_fkey' AND conrelid = 'public.omnia_rescisoes'::regclass) THEN
    ALTER TABLE public.omnia_rescisoes RENAME CONSTRAINT omnia_rescisoes_created_by_fkey TO omnia_demissoes_created_by_fkey;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'omnia_rescisoes_status_id_fkey' AND conrelid = 'public.omnia_rescisoes'::regclass)
     AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'omnia_demissoes_status_id_fkey' AND conrelid = 'public.omnia_rescisoes'::regclass) THEN
    ALTER TABLE public.omnia_rescisoes RENAME CONSTRAINT omnia_rescisoes_status_id_fkey TO omnia_demissoes_status_id_fkey;
  END IF;
END $$;

