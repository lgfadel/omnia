CREATE TABLE IF NOT EXISTS public.omnia_atas (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  description TEXT,
  meeting_date DATE,
  status_id UUID NOT NULL REFERENCES public.omnia_statuses(id),
  condominium_id UUID REFERENCES public.omnia_condominiums(id),
  secretary_id UUID REFERENCES public.omnia_users(id),
  responsible_id UUID REFERENCES public.omnia_users(id),
  created_by UUID REFERENCES public.omnia_users(id),
  ticket TEXT,
  tags TEXT[] DEFAULT ARRAY[]::TEXT[],
  comment_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.omnia_comments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ata_id UUID NOT NULL REFERENCES public.omnia_atas(id) ON DELETE CASCADE,
  author_id UUID NOT NULL REFERENCES public.omnia_users(id),
  created_by UUID REFERENCES public.omnia_users(id),
  body TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.omnia_attachments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ata_id UUID REFERENCES public.omnia_atas(id) ON DELETE CASCADE,
  comment_id UUID REFERENCES public.omnia_comments(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  url TEXT NOT NULL,
  size_kb NUMERIC,
  mime_type TEXT,
  uploaded_by UUID REFERENCES public.omnia_users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.omnia_ticket_recurrences (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  title TEXT NOT NULL,
  description TEXT,
  status_id UUID NOT NULL REFERENCES public.omnia_ticket_statuses(id),
  priority TEXT NOT NULL DEFAULT 'MEDIA',
  frequency TEXT NOT NULL DEFAULT 'WEEKLY',
  interval INTEGER NOT NULL DEFAULT 1,
  start_date DATE NOT NULL DEFAULT CURRENT_DATE,
  end_type TEXT NOT NULL DEFAULT 'NEVER',
  end_date DATE,
  occurrence_limit INTEGER,
  generated_occurrences INTEGER NOT NULL DEFAULT 0,
  next_occurrence_date DATE,
  is_active BOOLEAN NOT NULL DEFAULT true,
  is_private BOOLEAN NOT NULL DEFAULT false,
  tags TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  assigned_to UUID REFERENCES public.omnia_users(id),
  created_by UUID REFERENCES public.omnia_users(id),
  template_ticket_id UUID,
  ticket_octa TEXT,
  oportunidade_id UUID,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.omnia_tickets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  title TEXT NOT NULL,
  description TEXT,
  status_id UUID NOT NULL REFERENCES public.omnia_ticket_statuses(id),
  priority TEXT NOT NULL DEFAULT 'MEDIA',
  due_date DATE,
  assigned_to UUID REFERENCES public.omnia_users(id),
  created_by UUID REFERENCES public.omnia_users(id),
  is_private BOOLEAN NOT NULL DEFAULT false,
  tags TEXT[] DEFAULT ARRAY[]::TEXT[],
  comment_count INTEGER NOT NULL DEFAULT 0,
  attachment_count INTEGER NOT NULL DEFAULT 0,
  recurrence_id UUID REFERENCES public.omnia_ticket_recurrences(id),
  recurrence_occurrence INTEGER,
  ticket_octa TEXT,
  oportunidade_id UUID,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'omnia_ticket_recurrences_template_ticket_id_fkey'
      AND conrelid = 'public.omnia_ticket_recurrences'::regclass
  ) THEN
    ALTER TABLE public.omnia_ticket_recurrences
      ADD CONSTRAINT omnia_ticket_recurrences_template_ticket_id_fkey
      FOREIGN KEY (template_ticket_id) REFERENCES public.omnia_tickets(id);
  END IF;
END $$;

